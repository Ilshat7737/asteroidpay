// ISO 3166-1 alpha-2 -> flag emoji, built from the two Regional Indicator
// Symbol code points (U+1F1E6 = 'A') rather than hand-picking 178 emoji —
// exact and impossible to typo per-country this way. "XK" (Kosovo) has no
// official ISO code/flag emoji; falls back to a plain placeholder since
// most platforms don't render one for it anyway.
export function flagEmoji(code: string): string {
  if (code === "XK") return "🏳️";
  return code
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(0x1f1e6 + char.charCodeAt(0) - 65));
}
